package week04;

public class HW4_1CompareOperators {
    public static void main(String[] args) {
        // 4-1 비교 연산자
        int a = 10, b = 20;
        boolean isEqual = (a == b);

        System.out.println("a > b " + (a > b));
        System.out.println("a < b " + (a < b));
        System.out.println("a == b " + isEqual);
        System.out.println("a != b " + (a != b));
        System.out.println("a >= 10 " + (a >= 10));
        System.out.println("b <= 19 " + (b <= 19));
    }
}
