package week03;

public class Week03 {
    public static void main(String[] args) {
        int a = 7, b = 2;

        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);

        System.out.println((double) a / b);

        int i = 5;
        System.out.println(i++);
        System.out.println(i);
        System.out.println(++i);

        int score = 80;
        score += 10;
        System.out.println(score);
    }
}
